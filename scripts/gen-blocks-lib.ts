import type { Catalog, CatalogBlock, InputType } from '../packages/blocks/src/catalog-types.ts';

const INPUT_TYPES: ReadonlySet<string> = new Set<InputType>([
  'num',
  'text',
  'any',
  'bool',
  'numf',
  'textf',
  'combo',
  'time',
  'menu',
  'check',
  'days',
  'var',
  'stack',
]);
const SHAPES = new Set(['hat', 'stack', 'c', 'c2', 'cap', 'reporter', 'boolean']);

/** Placeholder names (`%NAME`) used in a block text, in order. */
export function placeholders(text: string): string[] {
  return [...text.matchAll(/%([A-Z][A-Z0-9_]*)/g)].map((m) => m[1]!);
}

/** Checks the catalog; returns a list of problems (empty = valid). */
export function validateCatalog(catalog: Catalog): string[] {
  const errors: string[] = [];
  const cats = new Set(catalog.categories.map((c) => c.id));
  const ops = new Map<number, string>();
  const ids = new Set<string>();
  for (const b of catalog.blocks) {
    const where = `block ${b.id ?? '?'} (op ${b.op})`;
    if (!Number.isInteger(b.op) || b.op <= 0 || b.op > 65535) errors.push(`${where}: invalid op`);
    if (ops.has(b.op)) errors.push(`${where}: op already used by ${ops.get(b.op)}`);
    ops.set(b.op, b.id);
    if (!/^[a-z][a-z0-9_]*$/.test(b.id ?? '')) errors.push(`${where}: invalid id`);
    if (ids.has(b.id)) errors.push(`${where}: duplicate id`);
    ids.add(b.id);
    if (!cats.has(b.cat)) errors.push(`${where}: unknown category ${b.cat}`);
    if (!SHAPES.has(b.shape)) errors.push(`${where}: unknown shape ${b.shape}`);
    const names = (b.inputs ?? []).map((i) => i.name);
    if (new Set(names).size !== names.length) errors.push(`${where}: duplicate input names`);
    for (const input of b.inputs ?? []) {
      if (!INPUT_TYPES.has(input.type))
        errors.push(`${where}: input ${input.name} has unknown type ${input.type}`);
      if (input.type === 'menu' && !input.options?.length)
        errors.push(`${where}: menu ${input.name} needs options`);
      if (input.type === 'stack' && !['c', 'c2'].includes(b.shape))
        errors.push(`${where}: only c blocks have substacks`);
    }
    for (const lang of ['en', 'cs'] as const) {
      if (typeof b[lang] !== 'string' || !b[lang]) {
        errors.push(`${where}: missing ${lang} text`);
        continue;
      }
      const used = placeholders(b[lang]);
      if ([...used].sort().join() !== [...names].sort().join()) {
        errors.push(`${where}: ${lang} text placeholders [${used}] must match inputs [${names}]`);
      }
    }
  }
  return errors;
}

export function normalize(raw: unknown): Catalog {
  const c = raw as Catalog;
  return {
    version: c.version,
    categories: c.categories,
    blocks: c.blocks.map((b) => ({ ...b, inputs: b.inputs ?? [] })),
  };
}

const HEADER =
  'AUTO-GENERATED by scripts/gen-blocks.ts from packages/blocks/catalog.yaml. Do not edit.';

export function generateTs(catalog: Catalog): string {
  const blocks = catalog.blocks.map((b) => JSON.stringify(b)).join(',\n  ');
  const ops = catalog.blocks.map((b) => `  ${b.id}: ${b.op},`).join('\n');
  return `// ${HEADER}
import type { CatalogBlock, CatalogCategory } from '../catalog-types';

export const CATALOG_VERSION = ${catalog.version};

export const CATEGORIES: readonly CatalogCategory[] = ${JSON.stringify(catalog.categories, null, 2)};

export const BLOCKS: readonly CatalogBlock[] = [
  ${blocks},
];

export const OP = {
${ops}
} as const;

export type BlockId = keyof typeof OP;
`;
}

function pascal(id: string): string {
  return id
    .split('_')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}

function isTrigger(b: CatalogBlock): boolean {
  return b.shape === 'hat' && b.id !== 'cb_define';
}

export function generateRust(catalog: Catalog): string {
  const blocks = [...catalog.blocks].sort((a, b) => a.op - b.op);
  const variants = blocks.map((b) => `    ${pascal(b.id)} = ${b.op},`).join('\n');
  const fromU16 = blocks
    .map((b) => `            ${b.op} => Some(Self::${pascal(b.id)}),`)
    .join('\n');
  const idArms = blocks.map((b) => `            Self::${pascal(b.id)} => "${b.id}",`).join('\n');
  const arity = blocks
    .map((b) => `            Self::${pascal(b.id)} => ${b.inputs.length},`)
    .join('\n');
  const list = (pred: (b: CatalogBlock) => boolean) => {
    const arms = blocks.filter(pred).map((b) => `Self::${pascal(b.id)}`);
    return arms.length ? `matches!(self, ${arms.join(' | ')})` : 'false';
  };
  const argMods = blocks
    .filter((b) => b.inputs.length > 0)
    .map((b) => {
      const consts = b.inputs
        .map((i, n) => `        pub const ${i.name}: usize = ${n};`)
        .join('\n');
      return `    pub mod ${b.id} {\n${consts}\n    }`;
    })
    .join('\n');
  return `// ${HEADER}
#![allow(dead_code, clippy::all)]

pub const CATALOG_VERSION: u32 = ${catalog.version};

/// Block opcodes of the compact script format (spec §9.3).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(u16)]
pub enum Op {
${variants}
}

impl Op {
    pub fn from_u16(v: u16) -> Option<Self> {
        match v {
${fromU16}
            _ => None,
        }
    }

    pub fn id(self) -> &'static str {
        match self {
${idArms}
        }
    }

    /// Number of declared inputs (custom block calls may have more arguments).
    pub fn arity(self) -> usize {
        match self {
${arity}
        }
    }

    /// Blocks marked with ⚠ (spec §5.6).
    pub fn is_dangerous(self) -> bool {
        ${list((b) => Boolean(b.danger))}
    }

    /// Hat blocks that start a script.
    pub fn is_trigger(self) -> bool {
        ${list(isTrigger)}
    }

    pub fn is_variadic(self) -> bool {
        ${list((b) => Boolean(b.variadic))}
    }
}

/// Argument positions of each block's inputs.
pub mod arg {
${argMods}
}
`;
}
